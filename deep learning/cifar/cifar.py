        data = d_decoded['data']
        labels = d_decoded['labels']
        # Reshape flat array to (num_samples, channels, height, width) then transpose to (num_samples, height, width, channels)
        data = data.reshape(-1, 3, 32, 32).transpose(0, 2, 3, 1)
        return data, np.array(labels)

