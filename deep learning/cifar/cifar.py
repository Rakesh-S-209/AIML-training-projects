# 🏗️ MobileNetV2 Transfer Learning Model (Faster Training)
def build_mobilenetv2_fast():
    inputs = layers.Input(shape=(32, 32, 3))

    # Resize to 224x224 for MobileNetV2 compatibility
    x = layers.Resizing(224, 224)(inputs)
    x = tf.keras.applications.mobilenet_v2.preprocess_input(x)

    # Base model (frozen - all layers frozen)
    base = tf.keras.applications.MobileNetV2(
        include_top=False, weights='imagenet', input_shape=(224, 224, 3)
    )
    base.trainable = False  # Freeze ALL base layers

    x = base(x, training=False)
    x = layers.GlobalAveragePooling2D()(x)
    # Simplified head - only 2 layers to train
    x = layers.Dense(64, activation='relu')(x)
    outputs = layers.Dense(10, activation='softmax')(x)

    model = models.Model(inputs=inputs, outputs=outputs)
    return model

mobilenet_model = build_mobilenetv2_fast()
