def predict_image(img):
    if img is None:
        return "No image uploaded", {}

    # Convert various input types (PIL, path string, array) safely to a numpy array
    if isinstance(img, str):
        img_pil = Image.open(img).convert('RGB')
        img_array = np.array(img_pil)
    elif isinstance(img, Image.Image):
        img_pil = img.convert('RGB')
        img_array = np.array(img_pil)
    else:
        img_array = np.array(img)

    # Convert to tensor and resize to (32, 32) as expected by the model's input layer
    img_tensor = tf.convert_to_tensor(img_array, dtype=tf.float32)
    img_resized = tf.image.resize(img_tensor, (32, 32))
    # Expand dims to create batch dimension (1, 32, 32, 3)
    img_batch = tf.expand_dims(img_resized, 0)

    # Make prediction (the model internally resizes and scales)
    predictions = model.predict(img_batch, verbose=0)[0]
    confidences = {class_names[i]: float(predictions[i]) for i in range(10)}
    top_label = class_names[np.argmax(predictions)]

    return f"Predicted Class: {top_label.upper()}", confidences

